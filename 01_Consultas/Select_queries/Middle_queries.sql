--9. Mostrar los dispositivos que han generado más alertas.
select DEVICES.DEVICE_ID, DEVICES.DEVICE_NAME
from SECURITY_EVENTS join DEVICES on SECURITY_EVENTS.DEVICE_ID = DEVICES.DEVICE_ID
where SECURITY_EVENTS.ALERT_ID is not null
group by DEVICES.DEVICE_ID, DEVICES.DEVICE_NAME
order by count(distinct ALERT_ID) desc;

--10. Obtener los incidentes abiertos y el número de alertas relacionadas con cada uno.
select INCIDENTS.INCIDENT_ID, INCIDENTS.RATING, INCIDENTS.CREATION_DATE, INCIDENTS.CLOSED_DATE, INCIDENTS.PRIORITY, INCIDENTS.STATE, count(distinct ALERTS.ALERT_ID)
from ALERTS join INCIDENTS on ALERTS.INCIDENT_ID = INCIDENTS.INCIDENT_ID
where upper(INCIDENTS.STATE) <> 'CLOSED'
group by INCIDENTS.INCIDENT_ID, INCIDENTS.RATING, INCIDENTS.CREATION_DATE, INCIDENTS.CLOSED_DATE, INCIDENTS.PRIORITY, INCIDENTS.STATE;

--11. Calcular el tiempo medio de resolución de incidentes por categoría.
select INCIDENTS.PRIORITY as EVENT_PRIORITY, avg(INCIDENTS.CLOSED_DATE - INCIDENTS.CREATION_DATE) as RESOLUTION_TIME_MEDIAN
from INCIDENTS
where INCIDENTS.CLOSED_DATE is not null
group by INCIDENTS.PRIORITY;

--12. Identificar usuarios que hayan registrado actividad desde varias direcciones IP en un intervalo temporal determinado.
select USERS.USER_ID, USERNAME, DEPARTMENT, CREATION_DATE, ACTUAL_STATE
from SECURITY_EVENTS join USERS on USERS.USER_ID = SECURITY_EVENTS.USER_ID
where SECURITY_EVENTS.TIMESTAMP between TO_TIMESTAMP('01/01/2026 00:00:00.000', 'DD/MM/YYYY HH24:MI:SS.FF') AND TO_TIMESTAMP('01/01/2027 00:00:00.000', 'DD/MM/YYYY HH24:MI:SS.FF')
group by USERS.USER_ID, USERNAME, DEPARTMENT, CREATION_DATE, ACTUAL_STATE
having count(distinct SECURITY_EVENTS.IP_ADDRESS) > 1;
