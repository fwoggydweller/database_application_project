--7. Obtener las direcciones IP que han generado más eventos de inicio de sesión fallidos.
select SECURITY_EVENTS.IP_ADDRESS
from SECURITY_EVENTS
where EVENT_TYPE_ID = 2
group by SECURITY_EVENTS.IP_ADDRESS
order by count(*) desc;

--8. Identificar los usuarios con mayor número de intentos fallidos de autenticación.
select USERS.USER_ID, USERS.USERNAME, USERS.DEPARTMENT
from EVENT_TYPES join SECURITY_EVENTS on EVENT_TYPES.EVENT_ID = SECURITY_EVENTS.EVENT_TYPE_ID
join USERS on USERS.USER_ID = SECURITY_EVENTS.USER_ID
where SECURITY_EVENTS.EVENT_TYPE_ID = 8
group by USERS.USER_ID, USERS.USERNAME, USERS.DEPARTMENT
order by count(*) desc;

